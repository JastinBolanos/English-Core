package com.example.domain.util

/**
 * Catálogo maestro de subcategorías ("el tipo del tipo").
 * Asocia subcategorías a palabras por ID/Rank o por lema sin alterar
 * ni desordenar la estructura original de las 2,815 palabras.
 */
object WordSubcategoryCatalog {
  private val subcategoryByRank = mutableMapOf<Int, String>()
  private val subcategoryByLemma = mutableMapOf<String, String>()

  private val categorySpecificSubcategories = mutableMapOf<Pair<String, String>, String>()
  private val categorySpecificSubcategoriesByRank = mutableMapOf<Pair<String, Int>, String>()

  private val subjectRanks = mutableSetOf<Int>()
  private val subjectLemmas = mutableSetOf<String>()

  init {
    loadConnectorSubcategories()
    loadSubjectSubcategories()
    loadVerbs1To500()
    loadNouns1To500()
    ModifierSubcategories.load()
  }

  fun isSubject(lemma: String, rank: Int): Boolean {
    val clean = lemma.lowercase().trim()
    return subjectRanks.contains(rank) || subjectLemmas.contains(clean)
  }

  fun getSubcategory(lemma: String, rank: Int, category: String? = null): String? {
    val clean = lemma.lowercase().trim()
    if (category != null) {
      val catSpecific = categorySpecificSubcategoriesByRank[Pair(category, rank)]
        ?: categorySpecificSubcategories[Pair(category, clean)]
      if (catSpecific != null) return catSpecific
      if (category.equals("Modificador", ignoreCase = true)) {
        return when {
          clean.endsWith("ly") -> "Modo y Grado"
          clean.any { it.isDigit() } -> "Artículos y Cantidad"
          else -> "Cualidad y Opinión"
        }
      }
    }
    return subcategoryByRank[rank] ?: subcategoryByLemma[clean]
  }

  fun registerSubcategory(rank: Int, subCategory: String) {
    subcategoryByRank[rank] = subCategory
  }

  fun registerSubcategory(lemma: String, subCategory: String) {
    subcategoryByLemma[lemma.lowercase().trim()] = subCategory
  }

  fun registerByRank(map: Map<Int, String>) {
    subcategoryByRank.putAll(map)
  }

  fun registerByLemma(map: Map<String, String>) {
    map.forEach { (k, v) -> subcategoryByLemma[k.lowercase().trim()] = v }
  }

  private fun addConnector(rank: Int, lemma: String, subCategory: String) {
    val clean = lemma.lowercase().trim()
    subcategoryByRank[rank] = subCategory
    subcategoryByLemma[clean] = subCategory
    categorySpecificSubcategoriesByRank[Pair("Conector", rank)] = subCategory
    categorySpecificSubcategories[Pair("Conector", clean)] = subCategory
  }

  private fun addSubject(rank: Int, lemma: String, subCategory: String) {
    val clean = lemma.lowercase().trim()
    subjectRanks.add(rank)
    subjectLemmas.add(clean)
    subcategoryByRank[rank] = subCategory
    subcategoryByLemma[clean] = subCategory
    categorySpecificSubcategoriesByRank[Pair("Sujeto", rank)] = subCategory
    categorySpecificSubcategories[Pair("Sujeto", clean)] = subCategory
  }

  private fun addSubjectLemma(lemma: String, subCategory: String) {
    val clean = lemma.lowercase().trim()
    subjectLemmas.add(clean)
    subcategoryByLemma[clean] = subCategory
    categorySpecificSubcategories[Pair("Sujeto", clean)] = subCategory
  }

  private fun addVerb(rank: Int, lemma: String, subCategory: String) {
    val clean = lemma.lowercase().trim()
    subcategoryByRank[rank] = subCategory
    subcategoryByLemma[clean] = subCategory
    categorySpecificSubcategoriesByRank[Pair("Verbo", rank)] = subCategory
    categorySpecificSubcategories[Pair("Verbo", clean)] = subCategory
  }

  private fun addNoun(rank: Int, lemma: String, subCategory: String) {
    val clean = lemma.lowercase().trim()
    subcategoryByRank[rank] = subCategory
    subcategoryByLemma[clean] = subCategory
    categorySpecificSubcategoriesByRank[Pair("Sustantivo", rank)] = subCategory
    categorySpecificSubcategories[Pair("Sustantivo", clean)] = subCategory
  }

  fun addModifier(rank: Int, lemma: String, subCategory: String) {
    val clean = lemma.lowercase().trim()
    subcategoryByRank[rank] = subCategory
    subcategoryByLemma[clean] = subCategory
    categorySpecificSubcategoriesByRank[Pair("Modificador", rank)] = subCategory
    categorySpecificSubcategories[Pair("Modificador", clean)] = subCategory
  }

